-- Миграция: виртуальные свечи и имена святых для генератора крещения
-- Запустить в SQL Editor в Supabase Dashboard

-- ─── Виртуальные свечи (посетители за день) ─────────────────────────────────
CREATE TABLE IF NOT EXISTS candle_lights (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  visitor_id  TEXT NOT NULL,
  lit_date    DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at  TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (visitor_id, lit_date)
);

CREATE INDEX IF NOT EXISTS idx_candle_lights_date ON candle_lights (lit_date);

-- ─── Имена святых (православный календарь) ───────────────────────────────────
CREATE TABLE IF NOT EXISTS saint_names (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name        TEXT NOT NULL,
  gender      TEXT NOT NULL CHECK (gender IN ('male', 'female')),
  month       INT NOT NULL CHECK (month BETWEEN 1 AND 12),
  day         INT NOT NULL CHECK (day BETWEEN 1 AND 31),
  saint_title TEXT NOT NULL,
  description TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_saint_names_date ON saint_names (month, day);
CREATE INDEX IF NOT EXISTS idx_saint_names_gender ON saint_names (gender);

ALTER TABLE candle_lights DISABLE ROW LEVEL SECURITY;
ALTER TABLE saint_names DISABLE ROW LEVEL SECURITY;

